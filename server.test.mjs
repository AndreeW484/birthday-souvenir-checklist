import { test } from 'node:test';
import assert from 'node:assert/strict';

test('demo: entrega, conflicto, deshacer y archivos privados', async () => {
  delete process.env.SUPABASE_URL;
  delete process.env.SUPABASE_SECRET_KEY;
  const { server } = await import('./server.mjs');
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  const base = `http://127.0.0.1:${server.address().port}`;
  try {
    const guests = await (await fetch(`${base}/api/invitados`)).json();
    assert.equal(guests.length, 4);
    assert.equal(guests.reduce((s,g)=>s+g.adultos,0), 7);
    assert.equal(guests.reduce((s,g)=>s+g.ninos,0), 2);
    const patch = data => fetch(`${base}/api/invitados/1`, { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(data) });
    assert.equal((await patch({ tipo:'adultos', cantidad: 1 })).status, 400);
    const delivered = await (await patch({ tipo:'adultos', cantidad: 1, expected_adultos:0, expected_ninos:0 })).json();
    assert.equal(delivered.entregado_por, null);
    assert.equal(delivered.entregado, true);
    assert.ok(Date.parse(delivered.fecha_entrega));
    assert.equal((await patch({ tipo:'adultos', cantidad: 1, expected_adultos:0, expected_ninos:0, entregado_por: 'Otra persona' })).status, 409);
    const undone = await (await patch({ tipo:'adultos', cantidad: 0, expected_adultos:1, expected_ninos:0 })).json();
    assert.equal(undone.fecha_entrega, null);
    assert.equal(undone.entregado_por, null);
    assert.equal((await fetch(`${base}/.env`)).status, 404);
    assert.equal((await fetch(`${base}/server.mjs`)).status, 404);
    assert.equal((await fetch(base)).status, 200);
    const groupPatch = data => fetch(base + '/api/invitados/4', { method: 'PATCH', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(data) });
    assert.equal((await groupPatch({tipo:'adultos', cantidad:4,expected_adultos:0, expected_ninos:0})).status,400);
    assert.equal((await groupPatch({tipo:'adultos', cantidad:-1,expected_adultos:0, expected_ninos:0})).status,400);
    assert.equal((await groupPatch({tipo:'adultos', cantidad:1.5,expected_adultos:0, expected_ninos:0})).status,400);
    const partial = await (await groupPatch({tipo:'adultos', cantidad:1,expected_adultos:0, expected_ninos:0})).json();
    assert.equal(partial.entregado,false);
    assert.equal(partial.cantidad_entregada,1);
    assert.equal(partial.adultos + partial.ninos,3);
    assert.equal((await groupPatch({tipo:'adultos', cantidad:2,expected_adultos:0, expected_ninos:0})).status,409);
    const complete = await (await groupPatch({tipo:'adultos', cantidad:2,expected_adultos:1, expected_ninos:0})).json();
    assert.equal(complete.entregado,false);
    assert.equal(complete.ninos_entregados,0);
    assert.equal((await groupPatch({tipo:'ninos',cantidad:2,expected_adultos:2,expected_ninos:0})).status,400);
    const child = await (await groupPatch({tipo:'ninos',cantidad:1,expected_adultos:2,expected_ninos:0})).json();
    assert.equal(child.entregado,true);
    assert.equal(child.cantidad_entregada,3);
    assert.equal(child.adultos_entregados,2);
    assert.equal(child.ninos_entregados,1);
    assert.equal((await groupPatch({tipo:'adultos',cantidad:1,expected_adultos:2,expected_ninos:0})).status,409);
    const corrected = await (await groupPatch({tipo:'adultos', cantidad:1,expected_adultos:2, expected_ninos:1})).json();
    assert.equal(corrected.entregado,false);
    assert.equal(corrected.cantidad_entregada,2);
    assert.equal(corrected.ninos_entregados,1);
  } finally { await new Promise(resolve => server.close(resolve)); }
});
